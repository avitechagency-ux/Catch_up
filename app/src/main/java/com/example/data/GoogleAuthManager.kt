package com.example.data

import android.content.Context
import androidx.credentials.ClearCredentialStateRequest
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import androidx.credentials.exceptions.GetCredentialCancellationException
import com.example.BuildConfig
import com.google.android.libraries.identity.googleid.GetGoogleIdOption
import com.google.android.libraries.identity.googleid.GetSignInWithGoogleOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import com.google.firebase.FirebaseApp
import com.google.firebase.auth.FirebaseAuth
import com.google.firebase.auth.GoogleAuthProvider
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.tasks.await
import kotlinx.coroutines.withContext
import java.security.MessageDigest
import java.util.Locale

/**
 * Represents an authenticated Google user identity returned by Credential Manager / Firebase Auth.
 */
data class GoogleAccountIdentity(
    val googleUserId: String,
    val email: String,
    val displayName: String = "",
    val photoUrl: String? = null,
    val idToken: String? = null
)

/**
 * Outcome of launching the Google Sign-In flow via Credential Manager + Firebase Auth.
 */
sealed class GoogleSignInOutcome {
    data class Success(val identity: GoogleAccountIdentity) : GoogleSignInOutcome()
    data object Cancelled : GoogleSignInOutcome()
    data class FallbackPickerNeeded(val reason: String) : GoogleSignInOutcome()
}

/**
 * Central manager for Google Sign-In (Android Credential Manager API + Firebase Authentication)
 * and persistent Google session state synchronized with Supabase user profiles.
 */
object GoogleAuthManager {

    private const val PREFS_NAME = "catch_up_prefs"
    private const val KEY_GOOGLE_USER_ID = "google_user_id"
    private const val KEY_GOOGLE_EMAIL = "google_email"
    private const val KEY_GOOGLE_DISPLAY_NAME = "google_display_name"
    private const val KEY_GOOGLE_PHOTO_URL = "google_photo_url"
    private const val KEY_GOOGLE_ID_TOKEN = "google_id_token"
    private const val KEY_RECENT_GOOGLE_ACCOUNTS = "recent_google_accounts_json"

    /**
     * Resolves the OAuth 2.0 Web Client ID from `BuildConfig.GOOGLE_WEB_CLIENT_ID` or
     * the `default_web_client_id` Android string resource generated by `google-services.json`.
     */
    fun resolveWebClientId(context: Context): String {
        val fromBuildConfig = runCatching {
            val field = BuildConfig::class.java.declaredFields.firstOrNull { it.name == "GOOGLE_WEB_CLIENT_ID" }
            field?.isAccessible = true
            (field?.get(null) as? String).orEmpty().trim()
        }.getOrDefault("")

        if (fromBuildConfig.isNotBlank() &&
            !fromBuildConfig.contains("your-google-web-client-id") &&
            fromBuildConfig.endsWith(".apps.googleusercontent.com")
        ) {
            return fromBuildConfig
        }

        val resId = context.resources.getIdentifier("default_web_client_id", "string", context.packageName)
        if (resId != 0) {
            val fromRes = runCatching { context.getString(resId).trim() }.getOrDefault("")
            if (fromRes.isNotBlank() && !fromRes.contains("your-google-web-client-id")) {
                return fromRes
            }
        }
        return ""
    }

    /**
     * Generates a deterministic, URL-safe unique Google user ID from a Google subject ID or email.
     */
    fun deriveGoogleUserId(email: String, explicitGoogleUid: String? = null): String {
        val cleanExplicit = explicitGoogleUid?.trim().orEmpty()
        if (cleanExplicit.isNotBlank()) return cleanExplicit
        val normalizedEmail = email.trim().lowercase(Locale.US)
        if (normalizedEmail.isBlank()) return "google_user_anonymous"
        val digest = MessageDigest.getInstance("SHA-256")
            .digest("catchup_google_uid:$normalizedEmail".toByteArray(Charsets.UTF_8))
            .joinToString("") { "%02x".format(it) }
            .take(24)
        return "google_$digest"
    }

    /**
     * Launches Google Sign-In using Android's Credential Manager API (`GetGoogleIdOption` /
     * `GetSignInWithGoogleOption`) and exchanges the Google ID token with Firebase Auth if configured.
     *
     * If Credential Manager is not configured with a Web Client ID / SHA-1 for the current APK build
     * (e.g. a debug APK downloaded from GitHub Actions or an emulator without Play Services credentials),
     * returns [GoogleSignInOutcome.FallbackPickerNeeded] so the UI can seamlessly present the Google
     * account selector sheet without blocking the user.
     */
    suspend fun signInWithCredentialManager(context: Context): GoogleSignInOutcome {
        val webClientId = resolveWebClientId(context)
        if (webClientId.isBlank()) {
            return GoogleSignInOutcome.FallbackPickerNeeded("Web Client ID not configured in BuildConfig or google-services.json")
        }

        val credentialManager = CredentialManager.create(context)

        // 1. Try bottom-sheet GetGoogleIdOption first, then explicit GetSignInWithGoogleOption
        val googleIdOption = GetGoogleIdOption.Builder()
            .setFilterByAuthorizedAccounts(false)
            .setServerClientId(webClientId)
            .setAutoSelectEnabled(false)
            .build()

        val signInWithGoogleOption = GetSignInWithGoogleOption.Builder(webClientId)
            .build()

        val primaryRequest = GetCredentialRequest.Builder()
            .addCredentialOption(googleIdOption)
            .build()

        val fallbackRequest = GetCredentialRequest.Builder()
            .addCredentialOption(signInWithGoogleOption)
            .build()

        val response = try {
            credentialManager.getCredential(context = context, request = primaryRequest)
        } catch (cancelEx: GetCredentialCancellationException) {
            return GoogleSignInOutcome.Cancelled
        } catch (_: Exception) {
            try {
                credentialManager.getCredential(context = context, request = fallbackRequest)
            } catch (cancelEx2: GetCredentialCancellationException) {
                return GoogleSignInOutcome.Cancelled
            } catch (ex: Exception) {
                return GoogleSignInOutcome.FallbackPickerNeeded(ex.localizedMessage ?: "Credential Manager unavailable")
            }
        }

        val credential = response.credential
        if (credential is CustomCredential &&
            credential.type == GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL
        ) {
            return try {
                val googleIdTokenCredential = GoogleIdTokenCredential.createFrom(credential.data)
                val rawIdToken = googleIdTokenCredential.idToken
                val email = googleIdTokenCredential.id.trim()
                val displayName = googleIdTokenCredential.displayName?.trim().orEmpty()
                val photoUrl = googleIdTokenCredential.profilePictureUri?.toString()

                // Exchange with Firebase Auth if FirebaseApp is initialized
                val firebaseUser = signInToFirebaseWithIdToken(context, rawIdToken)
                val resolvedUid = firebaseUser?.uid?.takeIf { it.isNotBlank() }
                    ?: extractSubFromJwt(rawIdToken)
                    ?: deriveGoogleUserId(email)
                val resolvedEmail = firebaseUser?.email?.takeIf { it.isNotBlank() } ?: email
                val resolvedName = firebaseUser?.displayName?.takeIf { it.isNotBlank() }
                    ?: displayName.ifBlank { deriveDisplayNameFromEmail(resolvedEmail) }
                val resolvedPhoto = firebaseUser?.photoUrl?.toString() ?: photoUrl

                val identity = GoogleAccountIdentity(
                    googleUserId = resolvedUid,
                    email = resolvedEmail,
                    displayName = resolvedName,
                    photoUrl = resolvedPhoto,
                    idToken = rawIdToken
                )
                saveGoogleIdentity(context, identity)
                GoogleSignInOutcome.Success(identity)
            } catch (e: Exception) {
                GoogleSignInOutcome.FallbackPickerNeeded(e.localizedMessage ?: "Invalid Google ID token")
            }
        }

        return GoogleSignInOutcome.FallbackPickerNeeded("Unsupported credential type")
    }

    private suspend fun signInToFirebaseWithIdToken(
        context: Context,
        idToken: String
    ): com.google.firebase.auth.FirebaseUser? = withContext(Dispatchers.IO) {
        try {
            val apps = FirebaseApp.getApps(context)
            if (apps.isEmpty()) {
                runCatching { FirebaseApp.initializeApp(context) }
            }
            if (FirebaseApp.getApps(context).isEmpty()) return@withContext null
            val firebaseAuth = FirebaseAuth.getInstance()
            val credential = GoogleAuthProvider.getCredential(idToken, null)
            val authResult = firebaseAuth.signInWithCredential(credential).await()
            authResult.user
        } catch (_: Exception) {
            null
        }
    }

    private fun extractSubFromJwt(jwt: String): String? {
        return runCatching {
            val parts = jwt.split(".")
            if (parts.size < 2) return null
            val payloadBytes = android.util.Base64.decode(
                parts[1],
                android.util.Base64.URL_SAFE or android.util.Base64.NO_WRAP or android.util.Base64.NO_PADDING
            )
            val json = org.json.JSONObject(String(payloadBytes, Charsets.UTF_8))
            val sub = json.optString("sub", "").trim()
            if (sub.isNotBlank()) "google_$sub" else null
        }.getOrNull()
    }

    fun deriveDisplayNameFromEmail(email: String): String {
        val localPart = email.substringBefore("@").trim()
        if (localPart.isBlank()) return ""
        return localPart
            .split(Regex("[._\\-+0-9]+"))
            .filter { it.isNotBlank() }
            .joinToString(" ") { part ->
                part.lowercase(Locale.US).replaceFirstChar { it.titlecase(Locale.US) }
            }
            .trim()
    }

    /**
     * Completes Google Sign-In for a selected/entered Google account and persists the session.
     */
    fun completeGoogleSignInWithAccount(
        context: Context,
        email: String,
        displayName: String = "",
        photoUrl: String? = null,
        explicitGoogleUid: String? = null
    ): GoogleAccountIdentity {
        val cleanEmail = email.trim().lowercase(Locale.US)
        val cleanName = displayName.trim().ifBlank { deriveDisplayNameFromEmail(cleanEmail) }
        val uid = deriveGoogleUserId(cleanEmail, explicitGoogleUid)
        val identity = GoogleAccountIdentity(
            googleUserId = uid,
            email = cleanEmail,
            displayName = cleanName,
            photoUrl = photoUrl?.takeIf { it.isNotBlank() }
        )
        saveGoogleIdentity(context, identity)
        return identity
    }

    /**
     * Persists the authenticated Google account session so the user stays signed in across app restarts.
     */
    fun saveGoogleIdentity(context: Context, identity: GoogleAccountIdentity) {
        val prefs = context.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
        prefs.edit()
            .putString(KEY_GOOGLE_USER_ID, identity.googleUserId)
            .putString(KEY_GOOGLE_EMAIL, identity.email)
            .putString(KEY_GOOGLE_DISPLAY_NAME, identity.displayName)
            .putString(KEY_GOOGLE_PHOTO_URL, identity.photoUrl ?: "")
            .putString(KEY_GOOGLE_ID_TOKEN, identity.idToken ?: "")
            .commit()

        recordRecentGoogleAccount(context, identity)
    }

    /**
     * Returns the currently active Google identity from Firebase Auth or persisted session storage.
     */
    fun getCurrentGoogleIdentity(context: Context): GoogleAccountIdentity? {
        // 1. Check FirebaseAuth currentUser if Firebase is initialized
        val firebaseUser = runCatching {
            if (FirebaseApp.getApps(context).isNotEmpty()) {
                FirebaseAuth.getInstance().currentUser
            } else null
        }.getOrNull()

        val prefs = context.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
        val savedUid = prefs.getString(KEY_GOOGLE_USER_ID, null)?.trim().orEmpty()
        val savedEmail = prefs.getString(KEY_GOOGLE_EMAIL, null)?.trim().orEmpty()
        val savedName = prefs.getString(KEY_GOOGLE_DISPLAY_NAME, null)?.trim().orEmpty()
        val savedPhoto = prefs.getString(KEY_GOOGLE_PHOTO_URL, null)?.trim()?.takeIf { it.isNotBlank() }
        val savedToken = prefs.getString(KEY_GOOGLE_ID_TOKEN, null)?.trim()?.takeIf { it.isNotBlank() }

        if (firebaseUser != null && !firebaseUser.email.isNullOrBlank()) {
            val email = firebaseUser.email!!.trim()
            return GoogleAccountIdentity(
                googleUserId = firebaseUser.uid.ifBlank { savedUid.ifBlank { deriveGoogleUserId(email) } },
                email = email,
                displayName = firebaseUser.displayName?.takeIf { it.isNotBlank() } ?: savedName,
                photoUrl = firebaseUser.photoUrl?.toString() ?: savedPhoto,
                idToken = savedToken
            )
        }

        if (savedEmail.isNotBlank() || savedUid.isNotBlank()) {
            return GoogleAccountIdentity(
                googleUserId = savedUid.ifBlank { deriveGoogleUserId(savedEmail) },
                email = savedEmail,
                displayName = savedName.ifBlank { deriveDisplayNameFromEmail(savedEmail) },
                photoUrl = savedPhoto,
                idToken = savedToken
            )
        }

        return null
    }

    /**
     * Returns true if a Google account identity is currently active in Firebase Auth or persisted session storage.
     */
    fun hasActiveSession(context: Context): Boolean {
        return getCurrentGoogleIdentity(context) != null
    }

    /**
     * Clears persisted local Google session fields synchronously.
     */
    fun clearLocalGoogleSession(context: Context) {
        context.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
            .edit()
            .putBoolean("is_logged_in", false)
            .remove(KEY_GOOGLE_USER_ID)
            .remove(KEY_GOOGLE_EMAIL)
            .remove(KEY_GOOGLE_DISPLAY_NAME)
            .remove(KEY_GOOGLE_PHOTO_URL)
            .remove(KEY_GOOGLE_ID_TOKEN)
            .commit()
    }

    /**
     * Returns true if the user has an active, authenticated session that should stay logged in across restarts.
     */
    fun isSessionAuthenticated(context: Context): Boolean {
        val prefs = context.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
        val isLoggedInFlag = prefs.getBoolean("is_logged_in", false)
        if (!isLoggedInFlag) return false
        val googleIdentity = getCurrentGoogleIdentity(context)
        if (googleIdentity != null) return true
        val legacyUser = prefs.getString("user_email", null) ?: prefs.getString("user_phone", null)
        return !legacyUser.isNullOrBlank()
    }

    /**
     * Remembers Google accounts previously used on this device so the fallback account picker
     * can offer 1-tap selection just like Android's native account chooser.
     */
    fun getRecentGoogleAccounts(context: Context): List<GoogleAccountIdentity> {
        val prefs = context.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
        val rawJson = prefs.getString(KEY_RECENT_GOOGLE_ACCOUNTS, null).orEmpty()
        val list = mutableListOf<GoogleAccountIdentity>()
        if (rawJson.isNotBlank()) {
            runCatching {
                val arr = org.json.JSONArray(rawJson)
                for (i in 0 until arr.length()) {
                    val obj = arr.optJSONObject(i) ?: continue
                    val email = obj.optString("email", "").trim()
                    if (email.isNotBlank()) {
                        list.add(
                            GoogleAccountIdentity(
                                googleUserId = obj.optString("googleUserId", "").ifBlank { deriveGoogleUserId(email) },
                                email = email,
                                displayName = obj.optString("displayName", "").ifBlank { deriveDisplayNameFromEmail(email) },
                                photoUrl = obj.optString("photoUrl", "").takeIf { it.isNotBlank() }
                            )
                        )
                    }
                }
            }
        }
        return list
    }

    private fun recordRecentGoogleAccount(context: Context, identity: GoogleAccountIdentity) {
        if (identity.email.isBlank()) return
        val existing = getRecentGoogleAccounts(context)
            .filterNot { it.email.equals(identity.email, ignoreCase = true) }
        val updated = listOf(identity) + existing.take(4)
        val arr = org.json.JSONArray()
        updated.forEach { acc ->
            val obj = org.json.JSONObject()
            obj.put("googleUserId", acc.googleUserId)
            obj.put("email", acc.email)
            obj.put("displayName", acc.displayName)
            obj.put("photoUrl", acc.photoUrl ?: "")
            arr.put(obj)
        }
        context.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
            .edit()
            .putString(KEY_RECENT_GOOGLE_ACCOUNTS, arr.toString())
            .apply()
    }

    /**
     * Signs out of the Google session (Firebase Auth + Credential Manager state + local preferences)
     * and revokes the active Supabase session.
     */
    suspend fun signOut(context: Context) {
        withContext(Dispatchers.IO) {
            // 1. Sign out of Firebase Auth if initialized
            runCatching {
                if (FirebaseApp.getApps(context).isNotEmpty()) {
                    FirebaseAuth.getInstance().signOut()
                }
            }

            // 2. Clear Credential Manager credential state
            runCatching {
                val credentialManager = CredentialManager.create(context)
                credentialManager.clearCredentialState(ClearCredentialStateRequest())
            }

            // 3. Clear persisted Google session & login state in SharedPreferences
            runCatching {
                context.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
                    .edit()
                    .putBoolean("is_logged_in", false)
                    .remove(KEY_GOOGLE_USER_ID)
                    .remove(KEY_GOOGLE_EMAIL)
                    .remove(KEY_GOOGLE_DISPLAY_NAME)
                    .remove(KEY_GOOGLE_PHOTO_URL)
                    .remove(KEY_GOOGLE_ID_TOKEN)
                    .commit()
            }

            // 4. Revoke Supabase session
            runCatching {
                SupabaseRepository.revokeCurrentSession()
            }
        }
    }
}
